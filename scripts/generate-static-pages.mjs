import { build } from "esbuild";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const projectRoot = process.cwd();
const temporaryDirectory = await mkdtemp(join(tmpdir(), "ritika-static-pages-"));
const bundlePath = join(temporaryDirectory, "static-pages.cjs");
const outputPath = resolve(projectRoot, "worker/generated-pages.ts");
const require = createRequire(import.meta.url);

try {
  await build({
    absWorkingDir: projectRoot,
    bundle: true,
    entryPoints: ["scripts/static-page-entry.tsx"],
    format: "cjs",
    jsx: "automatic",
    outfile: bundlePath,
    platform: "node",
  });

  const generated = require(bundlePath);
  const source =
    `// Generated by scripts/generate-static-pages.mjs. Do not edit directly.\n` +
    `export const HOME_BODY = ${JSON.stringify(generated.homeBody)};\n` +
    `export const CONTACT_BODY = ${JSON.stringify(generated.contactBody)};\n`;

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
} finally {
  await rm(temporaryDirectory, { force: true, recursive: true });
}
